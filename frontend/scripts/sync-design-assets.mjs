// Copies the approved Lamma design system from frontend-reference/ into the React app (P-017).
// The reference folder is READ-ONLY: this script only reads from it and never writes there.
// Re-run with `npm run sync:design` if the reference design is updated (with founder approval).
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..");
const ref = join(app, "..", "frontend-reference", "Lamma-UI-Design");

const banner = (source) =>
  `/* GENERATED by scripts/sync-design-assets.mjs from frontend-reference/Lamma-UI-Design/${source}.\n   Do not edit here: change the reference (with founder approval) and re-run \`npm run sync:design\`. */\n`;

function ensure(dir) {
  mkdirSync(dir, { recursive: true });
  return dir;
}

// 1) Fonts + licences, logos -> public/
const fonts = ensure(join(app, "public", "fonts"));
for (const f of readdirSync(join(ref, "assets", "fonts"))) copyFileSync(join(ref, "assets", "fonts", f), join(fonts, f));
const logos = ensure(join(app, "public", "logo"));
for (const f of readdirSync(join(ref, "assets", "logo"))) copyFileSync(join(ref, "assets", "logo", f), join(logos, f));
copyFileSync(join(ref, "assets", "logo", "favicon.svg"), join(app, "public", "favicon.svg"));

// 2) CSS (same import order as the prototype's index.html); font URLs point at /fonts.
const styles = ensure(join(app, "src", "styles", "design-system"));
const css = ["tokens", "lamma", "cards", "orders", "catalog", "money", "shell", "extras"];
for (const name of css) {
  const text = readFileSync(join(ref, "design-system", `${name}.css`), "utf8").replaceAll("../assets/fonts/", "/fonts/");
  writeFileSync(join(styles, `${name}.css`), banner(`design-system/${name}.css`) + text);
}
writeFileSync(
  join(styles, "prototype-app.css"),
  banner("app/app.css") + readFileSync(join(ref, "app", "app.css"), "utf8"),
);

// 3) Icons (Tabler, MIT) and illustrations as ES modules.
const icons = ensure(join(app, "src", "assets", "icons"));
const iconsJs = readFileSync(join(ref, "design-system", "icons.js"), "utf8").replace("window.LAMMA_ICONS=", "export const LAMMA_ICONS = ");
const iconsLicense = readFileSync(join(ref, "design-system", "icons", "LICENSE"), "utf8");
writeFileSync(join(icons, "iconData.js"), banner("design-system/icons.js") + `/*\n${iconsLicense}*/\n` + iconsJs);

const art = ensure(join(app, "src", "assets", "illustrations"));
let artJs = readFileSync(join(ref, "design-system", "illustrations.js"), "utf8");
artJs = artJs
  .replace(/\(function \(\) \{\s*/, "")
  .replace("window.LammaArt = {", "export const LammaArt = {")
  .replace(/\}\)\(\);\s*$/, "");
writeFileSync(join(art, "lammaArt.js"), banner("design-system/illustrations.js") + artJs);

console.log("Design assets synced from frontend-reference (read-only).");
